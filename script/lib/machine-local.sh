# Machine-local files, relative to $HOME — the single source of truth for
# bin/dot-doctor (what it reports) and 1password/functions.zsh (what
# local-backup packs). Plain POSIX sh assignments so both bash and zsh can
# source it; exported so the consumers see them.
# shellcheck shell=sh

# Packed into the `dotfiles: <hostname>` Document by local-backup.
export dotfiles_backup_files='
.localrc
.ssh/config.local
.config/1Password/ssh/agent.toml
.local/share/atuin/key
.gitconfig.identities
'

# Also packed, matched by glob: folder-scoped git identity files. Labels
# vary per machine (~/.gitconfig-pers, ~/.gitconfig-work, ...).
export dotfiles_backup_globs='
.gitconfig-*
'

# Machine-local but never backed up, each for its own reason:
#  - .gitconfig.local is regenerated by script/bootstrap (name/email prompt)
#  - .localgroups must exist before bootstrap, and `op` only exists after it
export dotfiles_unbacked_files='
.gitconfig.local
.localgroups
'
